#!/bin/zsh
# Install scribe-sync-server as a permanent macOS launch agent, plus a nightly ledger backup.
#
#   tools/mac_service/install.sh --dry-run   # print the plan, change nothing
#   tools/mac_service/install.sh             # install/update and (re)start
#   tools/mac_service/install.sh --uninstall # stop and remove both launch agents (data untouched)
#
# The binary and web bundle are COPIED into ~/Library/Application Support/Ignite so later
# `cargo build`s in the checkout never swap the running server underneath it. Data, token
# verifier and backups stay where they are (defaults below, override with env vars).
# The bearer token itself is never read by this script; the server only needs the verifier.
set -eu

REPO="${0:A:h:h:h}"
APP="$HOME/Library/Application Support/Ignite"
AGENTS="$HOME/Library/LaunchAgents"
LOGS="$HOME/Library/Logs"
IGNITE_HOME="${IGNITE_HOME:-$HOME/.ignite}"
DATA="${IGNITE_DATA_DIR:-$IGNITE_HOME/server-data}"
VERIFIER="${IGNITE_TOKEN_VERIFIER:-$IGNITE_HOME/token.verifier}"
BACKUPS="${IGNITE_BACKUP_DIR:-$IGNITE_HOME/backups/nightly}"
BIND="${IGNITE_BIND:-0.0.0.0:8787}"
KEEP="${IGNITE_BACKUP_KEEP:-14}"
BIN_SRC="${IGNITE_SERVER_BIN:-$REPO/target/release/scribe-sync-server}"
WEB_SRC="${IGNITE_WEB_ROOT:-$REPO/ignite/web/dist}"
# Optional: ignite-import (creates notebooks and sends notes to the Kindle), and the Kindle's text face (so Mac
# previews wrap text exactly like the device). Installed when present.
IMPORT_SRC="${IGNITE_IMPORT_BIN:-$REPO/target/release/ignite-import}"
FONT_SRC="$REPO/ignite/assets/typography/default-sans-v1.ttf"
SERVER_LABEL=com.ignite.sync-server
BACKUP_LABEL=com.ignite.backup
DOMAIN="gui/$(id -u)"

mode=install
case "${1:-}" in
  --dry-run) mode=dry ;;
  --uninstall) mode=uninstall ;;
  "") ;;
  *) echo "usage: $0 [--dry-run|--uninstall]" >&2; exit 2 ;;
esac

if [[ $mode == uninstall ]]; then
  for label in $SERVER_LABEL $BACKUP_LABEL; do
    launchctl bootout "$DOMAIN/$label" 2>/dev/null || true
    rm -f "$AGENTS/$label.plist"
  done
  echo "removed launch agents; data in $DATA and backups in $BACKUPS untouched"
  exit 0
fi

[[ -x $BIN_SRC ]] || { echo "missing server binary: $BIN_SRC (cargo +1.89.0 build --release -p scribe-sync-server)" >&2; exit 1; }
[[ -f $WEB_SRC/index.html ]] || { echo "missing web bundle: $WEB_SRC" >&2; exit 1; }
[[ -d $DATA ]] || { echo "missing data dir: $DATA" >&2; exit 1; }
[[ -f $VERIFIER ]] || { echo "missing token verifier: $VERIFIER" >&2; exit 1; }

cat <<EOF
plan:
  server binary  $BIN_SRC -> $APP/bin/scribe-sync-server
  web bundle     $WEB_SRC -> $APP/web
  importer       $([[ -x $IMPORT_SRC ]] && echo "$IMPORT_SRC -> $APP/bin/ignite-import" || echo "(not built, skipped)")
  text face      $FONT_SRC -> $APP/fonts/default-sans-v1.ttf
  data dir       $DATA (not moved)
  bind           $BIND
  launch agents  $AGENTS/$SERVER_LABEL.plist (RunAtLoad, KeepAlive)
                 $AGENTS/$BACKUP_LABEL.plist (daily 03:20, keep $KEEP)
  backups        $BACKUPS
  logs           $LOGS/ignite-sync-server.log, $LOGS/ignite-backup.log
EOF
[[ $mode == dry ]] && exit 0

mkdir -p "$APP/bin" "$APP/web" "$AGENTS" "$LOGS" "$BACKUPS"
# Copy to a temp name then rename: the running process keeps its old inode.
cp "$BIN_SRC" "$APP/bin/.scribe-sync-server.new" && mv -f "$APP/bin/.scribe-sync-server.new" "$APP/bin/scribe-sync-server"
rsync -a --delete "$WEB_SRC/" "$APP/web/"
if [[ -x $IMPORT_SRC ]]; then
  cp "$IMPORT_SRC" "$APP/bin/.ignite-import.new" && mv -f "$APP/bin/.ignite-import.new" "$APP/bin/ignite-import"
fi
mkdir -p "$APP/fonts" && cp "$FONT_SRC" "$APP/fonts/default-sans-v1.ttf"
cp "$REPO/tools/mac_service/backup.zsh" "$APP/backup.zsh"
chmod 700 "$APP/backup.zsh"

q() { print -r -- "${(qq)1}"; }
x() { local s=$1; s=${s//&/&amp;}; s=${s//</&lt;}; s=${s//>/&gt;}; print -r -- "$s"; }

cat > "$APP/run.zsh" <<EOF
#!/bin/zsh
# Generated by tools/mac_service/install.sh. Started by launchd ($SERVER_LABEL).
set -eu
exec $(q "$APP/bin/scribe-sync-server") --data-dir $(q "$DATA") --bind $(q "$BIND") \\
  --token-verifier-file $(q "$VERIFIER") --web-root $(q "$APP/web")
EOF
chmod 700 "$APP/run.zsh"

cat > "$AGENTS/$SERVER_LABEL.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>$SERVER_LABEL</string>
<key>ProgramArguments</key><array><string>/bin/zsh</string><string>$(x "$APP/run.zsh")</string></array>
<key>WorkingDirectory</key><string>$(x "$APP")</string>
<key>RunAtLoad</key><true/>
<key>KeepAlive</key><true/>
<key>ThrottleInterval</key><integer>10</integer>
<key>StandardOutPath</key><string>$(x "$LOGS/ignite-sync-server.log")</string>
<key>StandardErrorPath</key><string>$(x "$LOGS/ignite-sync-server.log")</string>
</dict></plist>
EOF

cat > "$AGENTS/$BACKUP_LABEL.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>$BACKUP_LABEL</string>
<key>ProgramArguments</key><array>
  <string>/bin/zsh</string><string>$(x "$APP/backup.zsh")</string>
  <string>$(x "$DATA")</string><string>$(x "$BACKUPS")</string><string>$KEEP</string>
</array>
<key>StartCalendarInterval</key><dict><key>Hour</key><integer>3</integer><key>Minute</key><integer>20</integer></dict>
<key>StandardOutPath</key><string>$(x "$LOGS/ignite-backup.log")</string>
<key>StandardErrorPath</key><string>$(x "$LOGS/ignite-backup.log")</string>
</dict></plist>
EOF
plutil -lint "$AGENTS/$SERVER_LABEL.plist" "$AGENTS/$BACKUP_LABEL.plist"

# A hand-started server (nohup, from the checkout) holds the port and the ledger lock.
for pid in $(pgrep -f 'scribe-sync-server --data-dir' || true); do
  cmd=$(ps -o command= -p "$pid" || true)
  if [[ $cmd != "$APP/bin/"* ]]; then
    echo "stopping hand-started server pid $pid"
    kill "$pid"
    for _ in {1..50}; do kill -0 "$pid" 2>/dev/null || break; sleep 0.1; done
  fi
done

for label in $SERVER_LABEL $BACKUP_LABEL; do
  launchctl bootout "$DOMAIN/$label" 2>/dev/null || true
done
sleep 0.5
launchctl bootstrap "$DOMAIN" "$AGENTS/$SERVER_LABEL.plist"
launchctl bootstrap "$DOMAIN" "$AGENTS/$BACKUP_LABEL.plist"
launchctl kickstart -k "$DOMAIN/$SERVER_LABEL"

port=${BIND##*:}
for _ in {1..50}; do
  # No unauthenticated health route: any HTTP answer (401 included) means it is listening.
  code=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$port/v1/libraries" 2>/dev/null || true)
  [[ $code != 000 && -n $code ]] && { echo "server answering on :$port (HTTP $code without token)"; exit 0; }
  sleep 0.2
done
echo "server did not answer on :$port; see $LOGS/ignite-sync-server.log" >&2
exit 1
